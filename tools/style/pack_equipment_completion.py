"""Pack original GLBs and runtime-rendered fallback icons, preserving file hashes."""
from pathlib import Path
import json,base64,hashlib
ROOT=Path(__file__).resolve().parents[2]
catalog=json.loads((ROOT/'assets/equipment-completion/catalog.json').read_text());models={};icons={}
for id,record in catalog.items():
 p=ROOT/record['file'];data=p.read_bytes();assert hashlib.sha256(data).hexdigest()==record['sha256'];models[id]=base64.b64encode(data).decode()
 icon=p.parent/'icon.png'
 if icon.exists():icons[id]='data:image/png;base64,'+base64.b64encode(icon.read_bytes()).decode()
(ROOT/'src/game/equipment-completion-assets.js').write_text('// Generated by tools/style/pack_equipment_completion.py. Original local Blender geometry.\nconst EQUIPMENT_COMPLETION_GLB='+json.dumps(models,separators=(',',':'))+';\nconst EQUIPMENT_COMPLETION_ICONS='+json.dumps(icons,separators=(',',':'))+';\n')
print('Packed',len(models),'authored meshes and',len(icons),'native fallback renders')
