from pathlib import Path
import json,base64,struct,hashlib
root=Path(__file__).resolve().parents[2]
paths={'M01':root/'assets/monsters/m01-battery-hopper/M01-battery-hopper.glb','M04':root/'assets/monsters/m04-low-frequency/M04-low-frequency.glb'}
for id in ['M02','M03','M05','M06','M07','M08','B01','B02','B03','B04']:paths[id]=root/'assets/monsters'/id.lower()/(id+'.glb')
packed={};metadata={}
for id,p in paths.items():
 b=p.read_bytes();n=struct.unpack_from('<I',b,12)[0];doc=json.loads(b[20:20+n]);assert not doc.get('images') and not doc.get('skins');assert all('KHR_materials_unlit'in m.get('extensions',{}) for m in doc['materials'])
 assert all('COLOR_0'in p['attributes'] for m in doc['meshes'] for p in m['primitives'])
 packed[id]=base64.b64encode(b).decode()
 height=3.0 if id=='M01' else 2.96 if id=='M04' else json.loads((p.parent/'blender.json').read_text())['height']
 metadata[id]={'height':height,'sha256':hashlib.sha256(b).hexdigest(),'bytes':len(b),'clips':[a['name'] for a in doc.get('animations',[])]}
(root/'src/game/street-monster-assets.js').write_text('// Generated by tools/style/pack_monsters.py. User-reference-derived, locally authored unlit assets.\nconst STREET_MONSTER_GLB='+json.dumps(packed,separators=(',',':'))+';\nconst STREET_MONSTER_META='+json.dumps(metadata,separators=(',',':'))+';\n')
(root/'assets/monsters/catalog.json').write_text(json.dumps(metadata,indent=2)+'\n')
print('Packed',len(packed),'models')
