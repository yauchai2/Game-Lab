"""Embed the three approved portrait comics; no layout or visual redesign of source art."""
from pathlib import Path
from PIL import Image
import base64
import hashlib
import json
ROOT=Path(__file__).resolve().parents[1]
ART=ROOT/'assets/prologue'
files=['01-afternoon','02-offbeat','03-reconnect']
assets=[]
receipt={}
for stem in files:
    source=ART/(stem+'-source.png')
    target=ART/(stem+'.webp')
    image=Image.open(source).convert('RGB')
    image.save(target,quality=90,method=6)
    assets.append({'src':'data:image/webp;base64,'+base64.b64encode(target.read_bytes()).decode(),'width':image.width,'height':image.height})
    for p in (source,target):
        receipt[p.name]={'sha256':hashlib.sha256(p.read_bytes()).hexdigest(),'bytes':p.stat().st_size,'width':image.width,'height':image.height}
(ROOT/'src/game/intro-comic-assets.js').write_text('/* Generated by tools/pack_intro_comic.py; approved artwork: assets/prologue. */\nconst INTRO_COMICS='+json.dumps(assets,separators=(',',':'))+';\n')
(ART/'manifest.json').write_text(json.dumps(receipt,indent=2)+'\n')
print('Embedded portrait comics:',sum(receipt[stem+'.webp']['bytes']for stem in files),'bytes')
