"""Prepare supplied title art and embed it for HTTP and offline builds.
Sources remain unchanged. Only transparent logo padding and web encodings change.
"""
from pathlib import Path
import base64
import hashlib
import json
import re
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / 'assets/brand/hello-static'
logo = Image.open(ART / 'logo-source.png').convert('RGBA')
box = logo.getchannel('A').point(lambda a: 255 if a > 8 else 0).getbbox()
logo = logo.crop(box)
logo.save(ART / 'logo.webp', quality=95, method=6)
background = Image.open(ART / 'rooftop-source.png').convert('RGB')
background.save(ART / 'rooftop.webp', quality=92, method=6)

def url(path):
    return 'data:image/webp;base64,' + base64.b64encode(path.read_bytes()).decode()

data = {'background': url(ART / 'rooftop.webp'), 'logoWidth': logo.width, 'logoHeight': logo.height}
(ROOT / 'src/game/title-screen-assets.js').write_text(
    '/* Generated by tools/pack_title_screen.py; source: assets/brand/hello-static. */\n'
    + 'const TITLE_SCREEN=' + json.dumps(data, separators=(',', ':')) + ';\n')
brand = ROOT / 'src/game/brand-asset.js'
text = brand.read_text()
text = re.sub(r'ASSET\.logo=.*?;\n', lambda _: 'ASSET.logo=' + json.dumps(url(ART / 'logo.webp')) + ';\n', text)
text = re.sub(r'^/\*.*?\*/', '/* Hello, Static! brand. Generated by tools/pack_title_screen.py. */', text)
brand.write_text(text)
page = ROOT / 'index.html'
text = page.read_text().replace('<title>Idle Hero</title>', '<title>Hello, Static! 哈囉，雜訊！</title>')
text = re.sub(r'<span class="boot-brand"><img src="[^"]+" alt="[^"]*">',
              lambda _: '<span class="boot-brand"><img src="' + url(ART / 'logo.webp') + '" alt="Hello, Static! 哈囉，雜訊！">', text)
text = text.replace('src/game/logo-3d-asset.js', 'src/game/title-screen-assets.js')
text = text.replace('background:#d2d9e7;color:#172751;display:grid;place-content:center',
                    'background:#4e77d0;color:#fff;display:grid;place-content:center')
text = text.replace('filter:drop-shadow(0 4px 0 #8492b0)', 'filter:none')
text = text.replace('#boot small{font-size:13px;color:#475778}', '#boot small{font-size:13px;color:#fff}')
page.write_text(text)
receipt = {'source': 'User-selected generated PNG artwork supplied in the title-screen request',
           'logo_crop': box, 'logo_size': logo.size, 'background_size': background.size,
           'files': {p.name: {'bytes': p.stat().st_size, 'sha256': hashlib.sha256(p.read_bytes()).hexdigest()}
                     for p in sorted(ART.iterdir()) if p.suffix in ('.png', '.webp')}}
(ART / 'manifest.json').write_text(json.dumps(receipt, indent=2) + '\n')
print('Prepared title artwork:', {p.name: p.stat().st_size for p in ART.glob('*.webp')})
