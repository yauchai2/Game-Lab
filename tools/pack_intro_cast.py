"""Pixelate the approved four-person art, then derive aligned visible-person layers.

192x341, 40 colors, no dithering; crop only white page margins, upscale 4x
with NEAREST. The source PNG and contour data remain reviewable.
"""
from pathlib import Path
from collections import deque
import base64, hashlib, io, json
from PIL import Image, ImageDraw
ROOT=Path(__file__).resolve().parents[1]
ART=ROOT/'assets/brand/hello-static/character-select'
SOURCE=ART/'source.png'
NATIVE=(192,341)
CROP=(0,70,192,301)
POLYGONS={
 'street':[(0,400),(380,400),(380,876),(325,880),(300,897),(274,922),(256,943),(245,976),(228,992),(236,1010),(208,1045),(225,1086),(210,1096),(214,1140),(210,1185),(193,1268),(0,1280)],
 'frost':[(390,350),(754,350),(754,680),(700,720),(655,775),(640,850),(680,935),(690,1030),(688,1105),(676,1155),(684,1198),(658,1235),(622,1253),(558,1245),(544,1221),(530,1183),(533,1120),(508,1080),(501,1003),(502,970),(500,925),(462,904),(425,885),(402,885),(384,860),(376,800)],
 'beep':[(760,650),(941,650),(941,1470),(605,1470),(583,1400),(606,1370),(627,1330),(635,1295),(654,1260),(668,1214),(659,1166),(669,1130),(694,1090),(699,1034),(713,1023),(700,996),(695,976),(699,953),(734,913),(729,900),(657,900),(634,870),(640,800),(688,740),(735,711),(760,650)],
 'volt':[(330,875),(390,877),(500,915),(500,975),(520,1000),(495,1044),(500,1092),(528,1133),(552,1174),(537,1225),(548,1260),(580,1300),(598,1342),(600,1415),(579,1450),(160,1450),(150,1400),(191,1340),(183,1290),(190,1255),(210,1200),(215,1150),(234,1110),(245,1090),(210,1055),(230,1018),(225,1000),(250,970),(255,947),(281,920)]
}
source=Image.open(SOURCE).convert('RGB')
small=source.resize(NATIVE,Image.Resampling.BOX).quantize(colors=40,method=Image.Quantize.MEDIANCUT,dither=Image.Dither.NONE).convert('RGBA')
# Flood only near-white background connected to the edge; keep light clothing.
seen=set();queue=deque((x,y)for x in range(NATIVE[0])for y in [0,NATIVE[1]-1])
queue.extend((x,y)for y in range(NATIVE[1])for x in [0,NATIVE[0]-1])
while queue:
 x,y=queue.popleft()
 if not(0<=x<NATIVE[0]and 0<=y<NATIVE[1])or(x,y)in seen:continue
 seen.add((x,y));r,g,b,a=small.getpixel((x,y))
 if min(r,g,b)<242 or max(r,g,b)-min(r,g,b)>10:continue
 small.putpixel((x,y),(r,g,b,0));queue.extend([(x+1,y),(x-1,y),(x,y+1),(x,y-1)])

def encode(image,name):
 high=image.resize((image.width*4,image.height*4),Image.Resampling.NEAREST)
 high.save(ART/(name+'.png'),optimize=True)
 buf=io.BytesIO();high.save(buf,format='PNG',optimize=True)
 return 'data:image/png;base64,'+base64.b64encode(buf.getvalue()).decode()

native=small.crop(CROP);native.save(ART/'native.png',optimize=True)
base=encode(native,'roster')
layers={};contours={}
for id,polygon in POLYGONS.items():
 mask=Image.new('L',NATIVE,0);d=ImageDraw.Draw(mask)
 d.polygon([(round(x/source.width*NATIVE[0]),round(y/source.height*NATIVE[1]))for x,y in polygon],fill=255)
 layer=small.copy();alpha=Image.frombytes('L',NATIVE,bytes(min(a,m)for a,m in zip(small.getchannel('A').tobytes(),mask.tobytes())))
 # Visible overlap cleanup: remove neighboring class clothing caught at a shared contour.
 if id in ('volt','beep'):
  for y in range(NATIVE[1]):
   for x in range(NATIVE[0]):
    r,g,b,a=layer.getpixel((x,y))
    if (id=='volt' and g>r*1.1 and g>b*1.3) or (id=='beep' and b>r*1.4 and b>g*1.2):alpha.putpixel((x,y),0)
 layer.putalpha(alpha);layers[id]=encode(layer.crop(CROP),id)
 contours[id]=[[round(x/source.width*100,3),round((y/source.height*NATIVE[1]-CROP[1])/(CROP[3]-CROP[1])*100,3)]for x,y in polygon]
asset={'src':base,'layers':layers,'polygons':contours,'width':native.width*4,'height':native.height*4,'nativeWidth':native.width,'nativeHeight':native.height}
(ROOT/'src/game/intro-cast-asset.js').write_text('/* Generated by tools/pack_intro_cast.py; approved white-background roster. */\nconst INTRO_CAST_ART='+json.dumps(asset,separators=(',',':'))+';\n')
(ART/'contours.json').write_text(json.dumps(POLYGONS,indent=2)+'\n')
receipt={'native':NATIVE,'crop':CROP,'upscale':4,'colors':40,'sampling':'BOX down, NEAREST up; no dithering','files':{p.name:{'bytes':p.stat().st_size,'sha256':hashlib.sha256(p.read_bytes()).hexdigest()}for p in sorted(ART.glob('*.png'))}}
(ART/'manifest.json').write_text(json.dumps(receipt,indent=2)+'\n')
print('Cast:',native.size,'->',(native.width*4,native.height*4),'runtime JS bytes:',(ROOT/'src/game/intro-cast-asset.js').stat().st_size)
# Review sheet only, outside repository.
sheet=Image.new('RGB',(768,231),'white')
for i,id in enumerate(POLYGONS):
 im=Image.open(ART/(id+'.png')).resize((192,231),Image.Resampling.NEAREST);sheet.paste(im,(i*192,0),im)
sheet.save('/tmp/cast-layer-review.png')
