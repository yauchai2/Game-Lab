#!/usr/bin/env python3
"""Identify Aki's baked white headset for conditional replacement; keep GLB intact.
Masks apply only while the uploaded headset is equipped. Original UVs, weights,
positions and animation tracks are shared unchanged; inspect the generated fit views.
"""
import hashlib,io,json,struct
from pathlib import Path
import numpy as np
from PIL import Image
root=Path(__file__).resolve().parents[2];data={}
id='aki';b=(root/'assets/characters'/f'{id}.glb').read_bytes();n=struct.unpack_from('<I',b,12)[0];g=json.loads(b[20:20+n]);start=28+n
width={'VEC3':3,'VEC2':2,'VEC4':4,'SCALAR':1};dtype={5126:'<f4',5123:'<u2',5121:'u1',5125:'<u4'}
def access(i):
 a=g['accessors'][i];v=g['bufferViews'][a['bufferView']];return np.frombuffer(b,dtype=dtype[a['componentType']],count=a['count']*width[a['type']],offset=start+v.get('byteOffset',0)+a.get('byteOffset',0)).reshape(a['count'],-1)
p=g['meshes'][0]['primitives'][0];pos=access(p['attributes']['POSITION']);uv=access(p['attributes']['TEXCOORD_0']);tri=access(p['indices']).reshape(-1,3)
v=g['bufferViews'][g['images'][0]['bufferView']];off=start+v.get('byteOffset',0);im=Image.open(io.BytesIO(b[off:off+v['byteLength']])).convert('RGB');pixels=np.asarray(im)
rgb=pixels[np.clip((uv[:,1]*im.height).astype(int),0,im.height-1),np.clip((uv[:,0]*im.width).astype(int),0,im.width-1)]/255
x,y,z=pos.T;neutral=(rgb.max(1)-rgb.min(1)<.18)&(rgb.mean(1)>.35)
region=((abs(x)>4.7)&(y>21.3)&(y<27)&(z>-3.7)&(z<2.8))|((y>26)&(y<30)&(z<1)&(z>-4))
remove=((neutral&region)[tri].sum(1)>=2)
# Include the old repair mark and dark cushions inside the measured earcup volume.
c=pos[tri].mean(1);ear=(abs(c[:,0])>4.8)&(c[:,1]>18.7)&(c[:,1]<24.8)&(c[:,2]>-3.5)&(c[:,2]<4.3);remove|=ear
roster=np.flatnonzero(remove).tolist();assert 100<len(roster)<4000
meta={'source_sha256':hashlib.sha256(b).hexdigest(),'vertices':len(pos),'triangles':len(tri),'remove':roster};data['aki_headphones']=meta
# Ordinary bulky earmuffs need the full light outer shell removed as well.
# Preserve dark hair and skin; the original uploaded-headset mask stays unchanged.
light_phone=(neutral|((rgb[:,2]>.5)&(rgb[:,1]>.4)&(rgb[:,0]<.55)))
outer_cup=(abs(x)>4.5)&(y>18)&(y<28)&(z>-5)&(z<6)
ordinary_remove=remove|((light_phone&outer_cup)[tri].sum(1)>=2)
ordinary_roster=np.flatnonzero(ordinary_remove).tolist();assert len(roster)<len(ordinary_roster)<4000
data['aki_ordinary_headphones']={**meta,'remove':ordinary_roster,'purpose':'Full bright outer baked headset shell only while ordinary tier-1 earmuffs are worn'}
(root/'assets/characters/equipment-masks.json').write_text(json.dumps(data,indent=2)+'\n')
(root/'src/game/characters-equipment-masks.js').write_text('// Generated by tools/model/prepare_equipment_masks.py; source GLB unchanged.\nconst CHARACTER_EQUIPMENT_MASKS = '+json.dumps(data,separators=(',',':'))+';\n')
print('Masked baked Aki headset triangles:',len(roster))
