#!/usr/bin/env python3
"""Pack derived GLBs for both development and the network-free standalone build.
python3 tools/model/pack_equipment.py DERIVED_DIR [DERIVED_DIR ...]
Name mapping is reviewed visually and kept in assets/equipment/source-map.json.
"""
import base64,hashlib,json,sys,struct,io
from pathlib import Path
from PIL import Image
root=Path(__file__).resolve().parents[2];out=root/'assets/equipment';sources=list(map(Path,sys.argv[1:]));mapping=json.loads((out/'source-map.json').read_text());packed={};icons={};records=[]
for key,stem in mapping.items():
 path=next(p/stem for p in sources if (p/(stem+'.glb')).exists());b=path.with_suffix('.glb').read_bytes();rec=json.loads(path.with_suffix('.json').read_text())
 assert hashlib.sha256(b).hexdigest()==rec['sha256'] and len(b)<500000 and rec['triangles']<=3100
 n=struct.unpack_from('<I',b,12)[0];g=json.loads(b[20:20+n]);assert b[:4]==b'glTF' and not g.get('skins') and not g.get('animations')
 assert all('uri'not in buffer for buffer in g['buffers']);assert all('bufferView'in img for img in g.get('images',[]))
 (out/(key+'.glb')).write_bytes(b);packed[key]=base64.b64encode(b).decode()
 if path.with_suffix('.png').exists():
  im=Image.open(path.with_suffix('.png')).convert('RGB');im.thumbnail((128,128));buf=io.BytesIO();im.save(buf,format='JPEG',quality=85);raw=buf.getvalue();(out/(key+'.jpg')).write_bytes(raw);icons[key]='data:image/jpeg;base64,'+base64.b64encode(raw).decode()
 rec={'id':key,**rec};records.append(rec)
manifest={'provenance':'User supplied Google Drive folder 12jSqAuk-xeRhGiEn-ciTk_OWUiqgZaQ0; original GLBs from two ZIPs, names matched against asset_list.zip reference images.','pipeline':'Blender: centered max-span 1, welded mesh, ~3000 triangles, 512px original base-color map, static GLB.','assets':records}
(out/'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
(root/'src/game/equipment-assets.js').write_text('// Generated by tools/model/pack_equipment.py from user-supplied meshes.\nconst EQUIPMENT_GLB = '+json.dumps(packed,separators=(',',':'))+';\nconst EQUIPMENT_ICONS = '+json.dumps(icons,separators=(',',':'))+';\n')
print('Packed',len(packed),'equipment meshes;',sum(r['bytes']for r in records),'GLB bytes')
