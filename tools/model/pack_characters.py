#!/usr/bin/env python3
"""Embed validated derived GLBs, keeping the offline build independent of requests."""
import base64,json,struct,sys,hashlib
from pathlib import Path
root=Path(__file__).resolve().parents[2];source=Path(sys.argv[1]);output=root/'src/game/characters-assets.js'
manifest=json.loads((source/'manifest.json').read_text());packed={}
for meta in manifest['assets']:
 b=(source/(meta['id']+'.glb')).read_bytes();n=struct.unpack_from('<I',b,12)[0];g=json.loads(b[20:20+n])
 assert b[:4]==b'glTF' and len(g['skins'])==1 and len(g['skins'][0]['joints'])==16
 assert {a['name']for a in g['animations']}==set(meta['animations'])
 assert hashlib.sha256(b).hexdigest()==meta['sha256'] and meta['triangles']<=14000 and len(b)<2200000
 packed[meta['id']]=base64.b64encode(b).decode()
output.write_text('// Generated by tools/model/pack_characters.py; Alan supplied meshes, derived locally.\nconst CHARACTER_GLB = '+json.dumps(packed,separators=(',',':'))+';\n')
p=root/'assets/characters';p.mkdir(parents=True,exist_ok=True)
for meta in manifest['assets']:(p/(meta['id']+'.glb')).write_bytes((source/(meta['id']+'.glb')).read_bytes())
(p/'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
print('Packed four skinned GLBs:',output.stat().st_size,'bytes')
