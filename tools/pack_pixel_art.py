"""Squash the approved title and prologue art to a low-resolution mosaic and embed it.

Sources in assets/ stay untouched. The game scales the small PNGs back up with
nearest-neighbour sampling, so the blocks are the visible look, not a filter.
"""
from pathlib import Path
import base64
import io
import json
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
BG = ROOT / 'assets/brand/hello-static'
PRO = ROOT / 'assets/prologue'
DOWN = 6          # source pixels per mosaic block for scenery
COLORS = 40       # a small palette keeps the blocks flat and the files tiny

# Panel boxes (x0, y0, x1, y1) measured from the cream gutter of each 941x1672 page.
PAGES = {
    '01-afternoon': [(19, 15, 922, 709), (19, 727, 922, 1062), (19, 1080, 922, 1654)],
    '02-offbeat': [(19, 13, 922, 434), (19, 455, 922, 1093), (19, 1115, 922, 1653)],
    '03-reconnect': [(19, 11, 922, 796), (19, 812, 922, 1655)],
}


def mosaic(image, block):
    small = image.resize((max(1, round(image.width / block)), max(1, round(image.height / block))), Image.BOX)
    return small.quantize(colors=COLORS, method=Image.MEDIANCUT, dither=Image.NONE).convert('RGB')


def png_url(image):
    buf = io.BytesIO()
    image.save(buf, 'PNG', optimize=True)
    return 'data:image/png;base64,' + base64.b64encode(buf.getvalue()).decode()


bg = mosaic(Image.open(BG / 'rooftop-source.png').convert('RGB'), DOWN)
logo = Image.open(BG / 'logo-source.png').convert('RGBA')
logo = logo.crop(logo.getchannel('A').point(lambda a: 255 if a > 8 else 0).getbbox())
logo_small = logo.resize((round(logo.width / 9), round(logo.height / 9)), Image.BOX)
alpha = logo_small.getchannel('A').point(lambda a: 255 if a > 110 else 0)
logo_rgb = logo_small.convert('RGB').quantize(colors=24, method=Image.MEDIANCUT, dither=Image.NONE).convert('RGB')
logo_small = logo_rgb.convert('RGBA')
logo_small.putalpha(alpha)

panels = []
for stem, boxes in PAGES.items():
    page = Image.open(PRO / (stem + '-source.png')).convert('RGB')
    row = []
    for box in boxes:
        crop = mosaic(page.crop(box), DOWN)
        row.append({'src': png_url(crop), 'w': crop.width, 'h': crop.height})
    panels.append(row)

data = {'bg': png_url(bg), 'bgW': bg.width, 'bgH': bg.height,
        'logo': png_url(logo_small), 'logoW': logo_small.width, 'logoH': logo_small.height,
        'pages': panels}
(ROOT / 'src/game/pixel-art-assets.js').write_text(
    '/* Generated by tools/pack_pixel_art.py; sources: assets/brand/hello-static, assets/prologue. */\n'
    'const PIXEL_ART=' + json.dumps(data, separators=(',', ':')) + ';\n')
print('title', bg.size, 'logo', logo_small.size,
      'panels', [[(p['w'], p['h']) for p in row] for row in panels],
      'bytes', (ROOT / 'src/game/pixel-art-assets.js').stat().st_size)
