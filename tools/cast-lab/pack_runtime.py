"""Embed the validated CastPose/CastSelect variants for the existing character reader."""
from pathlib import Path
import base64,json,hashlib
root=Path(__file__).resolve().parents[2]
manifest=json.loads((root/'assets/characters/cast-preview/models/manifest.json').read_text())
packed={p.stem:base64.b64encode(p.read_bytes()).decode() for p in sorted((root/'assets/characters/cast-preview/models').glob('*.glb'))}
assert set(packed)=={'aki','milo','ping','null'}
(root/'src/game/cast-assets.js').write_text('// Generated by tools/cast-lab/pack_runtime.py; original geometry and clips retained.\nconst CAST_CHARACTER_GLB='+json.dumps(packed,separators=(',',':'))+';\n')
print('Packed four cast variants for the native reader')
