"""Regenerate source registry/assets and world integration from reviewed tools."""
from pathlib import Path
import json,base64
R=Path(__file__).resolve().parents[2]
reg=json.loads((R/'assets/maps/series-registry.json').read_text());maps={r['id']:r for r in reg['maps']}
s='/* Generated by tools/maps/sync_series_assets.py. */\nconst ISLAND_REGISTRY='+json.dumps({'route':reg['route'],'maps':maps},ensure_ascii=False)+';\n'
for id,r in maps.items():s+='EQUIPMENT_COMPLETION_GLB.series_'+id+'='+json.dumps(base64.b64encode((R/r['model']).read_bytes()).decode())+';\n'
(R/'src/game/island-series-assets.js').write_text(s)
(R/'src/game/island-series-world.js').write_text((R/'tools/maps/fi02-layout-runtime.js').read_text()+'\n'+(R/'tools/maps/series-adapter.js').read_text())
